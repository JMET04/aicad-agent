ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / "learning" / "complex-servo-indexer-deep-run"
LOCKS = {"reviewOnly": True, "accepted": False, "ruleEnabled": False, "packagingGated": True}


def write(relative: str, text: str) -> str:
    path = BASE / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text.rstrip() + "\n", encoding="utf-8", newline="\n")
    return path.relative_to(ROOT).as_posix()


def entry(relative: str) -> dict[str, object]:
    path = ROOT / relative
    raw = path.read_bytes()
    return {"path": relative, "size": len(raw), "sha256": hashlib.sha256(raw).hexdigest()}


def slug(value: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")


def record(
    failure_id: str,
    alias: str,
    domain: str,
    check: str,
    symptom: str,
    root_cause: str,
    correction: str,
    rule_id: str,
    requirement: str,
    prevention: str,
    regression: str,
    red: str,
    green: str,
    sources: list[str],
    artifacts: list[str],
) -> dict[str, object]:
    stem = slug(failure_id)
    repro_path = write(f"repro/{stem}.txt", f"Reproduce {failure_id}: {check}. {symptom}")
    red_path = write(f"evidence/red-{stem}.txt", red)
    green_path = write(f"evidence/green-{stem}.txt", green)
    affected_path = write(
        f"affected/{stem}.txt",
        f"Corrected outcome for {failure_id}: {correction} Safety locks remain reviewOnly=true, accepted=false, ruleEnabled=false and packagingGated=true.",
    )
    return {
        "failureId": failure_id,
        "failureAlias": alias,
        "domain": domain,
        "failingCheck": check,
        "symptom": symptom,
        "rootCause": root_cause,
        "correction": correction,
        "candidateRule": {
            "id": rule_id,
            "requirement": requirement,
            "prevention": prevention,
            "regressionTest": regression,
            "safetyLocks": dict(LOCKS),
        },
        "reproducer": entry(repro_path),
        "evidenceClosure": {
            "policy": "exact_declared_evidence",
            "entries": [entry(red_path), entry(green_path)],
        },
        "sourceInputClosure": {
            "policy": "exact_declared_inputs",
            "entries": [entry(path) for path in sources],
        },
        "affectedArtifactClosure": {
            "policy": "exact_declared_artifacts",
            "entries": [entry(affected_path), *[entry(path) for path in artifacts]],
        },
    }


